-- Run this once in the Supabase SQL editor after the existing schema.sql.
-- The public site can read catalog rows; only the existing admin email may insert.

create table if not exists public.series (
  id bigint generated by default as identity primary key,
  slug text not null unique,
  title text not null,
  href text not null,
  cover text not null default '',
  category text not null default 'Manhwa',
  rating text,
  status text not null default 'Ongoing',
  pinned boolean not null default false,
  chapters jsonb not null default '[]'::jsonb,
  alternate_titles text[] not null default '{}',
  synopsis text,
  author text,
  artist text,
  publishers text[] not null default '{}',
  content_rating text,
  year integer,
  original_language text,
  demographics text[] not null default '{}',
  genres text[] not null default '{}',
  formats text[] not null default '{}',
  tags text[] not null default '{}',
  trackers jsonb not null default '[]'::jsonb,
  sources jsonb not null default '[]'::jsonb,
  facts jsonb not null default '{}'::jsonb,
  favorites text,
  review_count integer,
  page_number integer not null default 1,
  page_order integer not null default 0,
  created_at timestamptz not null default now(),
  updated_at timestamptz not null default now()
);

create index if not exists series_catalog_order_idx
  on public.series (page_number, page_order, title);

alter table public.series enable row level security;

grant select on public.series to anon, authenticated;
grant insert on public.series to authenticated;
grant usage, select on sequence public.series_id_seq to authenticated;

drop policy if exists "Public can read series" on public.series;
create policy "Public can read series"
  on public.series for select
  to anon, authenticated
  using (true);

drop policy if exists "Admin can add series" on public.series;
create policy "Admin can add series"
  on public.series for insert
  to authenticated
  with check (lower(auth.jwt() ->> 'email') = lower('clydhex@gmail.com'));
